/**
 * Which toolchain profile a manifest implies: any build targeting AVR
 * (emit hex/flash, profile avr, or an mcu) → embedded; emit wasm → wasm;
 * everything else (or no builds at all) → desktop.
 */
export function profileFromBuilds(pkg: { builds?: unknown }): ToolProfile {
  const builds = pkg.builds;
  if (!builds || typeof builds !== 'object') return 'desktop';
  for (const cfg of Object.values(builds as Record<string, Record<string, unknown>>)) {
    if (!cfg || typeof cfg !== 'object') continue;
    if (cfg.emit === 'flash' || cfg.emit === 'hex' || cfg.profile === 'avr' || cfg.mcu) return 'embedded';
    if (cfg.emit === 'wasm') return 'wasm';
  }
  return 'desktop';
}
